import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
df=pd.read_csv("/content/preprocessed_data.csv")
df

df["Brand"]=df["Brand"].replace({"toyota":"Toyota"})

df.drop(columns=["Brand_dup","Selling_Price_dup"],inplace=True)

"""count plot

"""

count=sns.countplot(data=df,x="Brand")
for c in count.containers:
  plt.bar_label(c,padding=3)
  plt.xticks(rotation=90)
plt.show()

"""PIE CHART"""

fuel_type_count=df["Fuel_Type"].value_counts()
plt.pie(fuel_type_count,labels=fuel_type_count.index,autopct="%1.1f%%")
plt.legend()
plt.show()

"""BAR CHART"""

owner_count=df["Owner"].value_counts()
plt.bar(owner_count.index,owner_count.values,color="yellow",edgecolor="black")
plt.xlabel("Owners")

"""HISTOGRAM"""

plt.hist(df['Driven_KMs'], bins=10, edgecolor='black')

plt.title("Histogram of Driven KMs")
plt.xlabel("Driven KMs")
plt.ylabel("Frequency")

plt.show()

"""BOX PLOT"""

sns.boxplot(y=df['Selling_Price'])

plt.title("Box Plot of Selling Price")
plt.ylabel("Selling Price")

plt.show()

"""HISTOGRAM PLOT"""

sns.histplot(df['Mileage_kmpl'], bins=10, kde=True)

plt.title("Histogram Plot of Mileage")
plt.xlabel("Mileage (kmpl)")
plt.ylabel("Count")

plt.show()

"""VIOLIN PLOT"""

sns.violinplot(y=df['Engine_CC'])

plt.title("Violin Plot of Engine CC")
plt.ylabel("Engine CC")

plt.show()

"""SCATTER PLOT"""

sns.scatterplot(x=df['Present_Price'],
                y=df['Selling_Price'])

plt.title("Present Price vs Selling Price")
plt.xlabel("Present Price")
plt.ylabel("Selling Price")

plt.show()

"""COUNT PLOT"""

sns.countplot(x='Fuel_Type',
              hue='Transmission',
              data=df)

plt.title("Fuel Type vs Transmission")
plt.xlabel("Fuel Type")
plt.ylabel("Count")

plt.show()

"""STACKED BAR CHART"""

data = pd.crosstab(df['Fuel_Type'], df['Transmission'])

data.plot(kind='bar', stacked=True)

plt.title("Stacked Bar Chart")
plt.xlabel("Fuel Type")
plt.ylabel("Count")

plt.show()

"""PAIRPLOT"""

sns.pairplot(df[['Selling_Price', 'Present_Price',
                 'Driven_KMs', 'Mileage_kmpl']])

plt.show()

data = df.select_dtypes(include='number')

sns.heatmap(data.corr(), annot=True, cmap='coolwarm')

plt.title("Correlation Heatmap")

plt.show()

"""JOINT PLOT"""

sns.jointplot(data=df,
              x='Present_Price',
              y='Selling_Price',
              hue='Fuel_Type')

plt.show()

"""BUBBLE CHART"""

plt.scatter(df['Present_Price'],
            df['Selling_Price'],
            s=df['Driven_KMs'] / 100,
            alpha=0.5)

plt.title("Bubble Chart")
plt.xlabel("Present Price")
plt.ylabel("Selling Price")

plt.show()

"""SCATTER PLOT WITH HUE AND SIZE


"""

sns.scatterplot(data=df,
                x='Present_Price',
                y='Selling_Price',
                hue='Fuel_Type',
                size='Driven_KMs',
                sizes=(20, 200))

plt.title("Scatter Plot with Hue and Size")
plt.show()

